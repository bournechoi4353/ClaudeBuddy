// Generates renderer/tray-icon.png — a tiny black crab silhouette suitable
// for the macOS menubar. We mark it as a template image at runtime so macOS
// auto-inverts for dark mode. Run with: node scripts/generate-tray-icon.js

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

// Mini crab silhouette — same 12×10 grid as the in-app crab, centered inside
// a 22×16 canvas. Eyes are cutouts (transparent) so the menubar background
// shows through, giving the silhouette real character.
const CRAB = [
  '......................',
  '......................',
  '......................',
  '.......OOOOOOOO.......',
  '.......O.OOOO.O.......',
  '.......OOOOOOOO.......',
  '.....OOOOOOOOOOOO.....',
  '.....OOOOOOOOOOOO.....',
  '.......OOOOOOOO.......',
  '.......OOOOOOOO.......',
  '.......OOOOOOOO.......',
  '.......O.O..O.O.......',
  '.......O.O..O.O.......',
  '......................',
  '......................',
  '......................',
];

const W = 22, H = 16;
const BLACK = [0x00, 0x00, 0x00, 0xff];
const TRANSPARENT = [0x00, 0x00, 0x00, 0x00];

const px = Buffer.alloc(W * H * 4);
for (let y = 0; y < H; y++) {
  for (let x = 0; x < W; x++) {
    const ch = CRAB[y] && CRAB[y][x];
    const c = ch === 'O' ? BLACK : TRANSPARENT;
    const idx = (y * W + x) * 4;
    px[idx] = c[0];
    px[idx + 1] = c[1];
    px[idx + 2] = c[2];
    px[idx + 3] = c[3];
  }
}

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xFFFFFFFF >>> 0;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xFF] ^ (c >>> 8);
  return (c ^ 0xFFFFFFFF) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, 'ascii');
  const crcBuf = Buffer.alloc(4);
  crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([len, typeBuf, data, crcBuf]);
}

const scanlines = Buffer.alloc(W * H * 4 + H);
for (let y = 0; y < H; y++) {
  scanlines[y * (W * 4 + 1)] = 0;
  px.copy(scanlines, y * (W * 4 + 1) + 1, y * W * 4, (y + 1) * W * 4);
}
const idat = zlib.deflateSync(scanlines);

const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(W, 0);
ihdr.writeUInt32BE(H, 4);
ihdr[8] = 8;
ihdr[9] = 6;

const sig = Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
const png = Buffer.concat([sig, chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0))]);

const out = path.join(__dirname, '..', 'renderer', 'tray-icon.png');
fs.writeFileSync(out, png);
console.log('wrote', out, png.length, 'bytes');

// Also write a 2x version for retina menubars (44x32). Generated by literally
// nearest-neighbor upscaling the same grid 2x.
const W2 = W * 2, H2 = H * 2;
const px2 = Buffer.alloc(W2 * H2 * 4);
for (let y = 0; y < H2; y++) {
  for (let x = 0; x < W2; x++) {
    const sx = Math.floor(x / 2);
    const sy = Math.floor(y / 2);
    const src = (sy * W + sx) * 4;
    const dst = (y * W2 + x) * 4;
    px2[dst] = px[src];
    px2[dst + 1] = px[src + 1];
    px2[dst + 2] = px[src + 2];
    px2[dst + 3] = px[src + 3];
  }
}
const scanlines2 = Buffer.alloc(W2 * H2 * 4 + H2);
for (let y = 0; y < H2; y++) {
  scanlines2[y * (W2 * 4 + 1)] = 0;
  px2.copy(scanlines2, y * (W2 * 4 + 1) + 1, y * W2 * 4, (y + 1) * W2 * 4);
}
const idat2 = zlib.deflateSync(scanlines2);
const ihdr2 = Buffer.alloc(13);
ihdr2.writeUInt32BE(W2, 0);
ihdr2.writeUInt32BE(H2, 4);
ihdr2[8] = 8;
ihdr2[9] = 6;
const png2 = Buffer.concat([sig, chunk('IHDR', ihdr2), chunk('IDAT', idat2), chunk('IEND', Buffer.alloc(0))]);
const out2 = path.join(__dirname, '..', 'renderer', 'tray-icon@2x.png');
fs.writeFileSync(out2, png2);
console.log('wrote', out2, png2.length, 'bytes');
